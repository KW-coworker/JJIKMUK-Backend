"""Build one reviewed file for the one-time human connection; no credentials or network."""
from pathlib import Path
import ast
import hashlib


def build(folder):
    connection=(folder/'connection.py').read_text(encoding='utf-8')
    connection=connection.split("\nif __name__ == '__main__':",1)[0]
    probe=(folder/'inspect_host.py').read_text(encoding='utf-8')
    spec=(folder/'backend-deploy.ssm.json').read_text(encoding='utf-8')
    old="(Path(__file__).parent / 'inspect_host.py').read_text(encoding='utf-8')"
    assert connection.count(old)==1
    connection=connection.replace(old,repr(probe))
    old="json.loads((Path(__file__).parent/'backend-deploy.ssm.json').read_bytes())"
    assert connection.count(old)==1
    connection=connection.replace(old,'json.loads('+repr(spec)+')')
    bootstrap=(folder/'bootstrap.py').read_text(encoding='utf-8')
    tree=ast.parse(bootstrap);lines=bootstrap.splitlines(keepends=True)
    imports=[n for n in tree.body if isinstance(n,ast.ImportFrom) and n.module=='connection']
    assert len(imports)==1
    node=imports[0];del lines[node.lineno-1:node.end_lineno]
    result='# Generated by build_bootstrap.py; source files are reviewed together.\n'+connection+'\n'+''.join(lines)
    compile(result,'connect_once.py','exec')
    return result


if __name__=='__main__':
    folder=Path(__file__).resolve().parent
    text=build(folder);(folder/'connect_once.py').write_text(text,encoding='utf-8',newline='\n')
    print(hashlib.sha256(text.encode()).hexdigest())
